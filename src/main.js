import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { createWorld } from './world.js';
import { setupUI } from './ui.js';
import { createSimulation, BUILDINGS } from './simulation.js';
import './style.css';

const canvas = document.querySelector('#world');
const renderer = new THREE.WebGLRenderer({canvas, antialias:true, powerPreference:'high-performance'});
renderer.setPixelRatio(Math.min(devicePixelRatio, 1.75));
renderer.setSize(innerWidth,innerHeight);
renderer.shadowMap.enabled=true;
renderer.shadowMap.type=THREE.PCFSoftShadowMap;
renderer.outputColorSpace=THREE.SRGBColorSpace;
renderer.toneMapping=THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure=1.02;
const scene=new THREE.Scene();
scene.background=new THREE.Color('#c3cfbd');
scene.fog=new THREE.Fog('#c3cfbd',100,235);
const camera=new THREE.PerspectiveCamera(39,innerWidth/innerHeight,0.1,400);
camera.position.set(65,64,76);
const controls=new OrbitControls(camera,canvas);
controls.target.set(0,1,0);
controls.enableDamping=true;
controls.dampingFactor=.07;
controls.minDistance=25;controls.maxDistance=140;
controls.maxPolarAngle=Math.PI*.46;
controls.mouseButtons={LEFT:THREE.MOUSE.PAN,MIDDLE:THREE.MOUSE.DOLLY,RIGHT:THREE.MOUSE.ROTATE};
scene.add(new THREE.HemisphereLight('#e5efdf','#526342',1.5));
const sun=new THREE.DirectionalLight('#fff0cc',2.8);
sun.position.set(-35,65,30);sun.castShadow=true;
sun.shadow.mapSize.set(2048,2048);
Object.assign(sun.shadow.camera,{left:-65,right:65,top:65,bottom:-65,near:1,far:180});
sun.shadow.normalBias=.055;sun.shadow.bias=-.0001;scene.add(sun);
const world=createWorld(THREE,scene);
const sim=createSimulation();
let selected=null;
const ui=setupUI({onBuild(type){selected=selected===type?null:type;sim.state.selected=selected;ui.selectBuilding(selected);ui.notify(selected?`${BUILDINGS[type].name}: elige un lugar en el valle. Esc para cancelar.`:'Construcción cancelada.');},onSpeed(n){sim.setSpeed(n);},onPause(){sim.togglePause();},onReset(){location.reload();},onRotate(){const p=camera.position.clone().sub(controls.target);p.applyAxisAngle(new THREE.Vector3(0,1,0),Math.PI/4);camera.position.copy(controls.target).add(p);}});
const ray=new THREE.Raycaster(), mouse=new THREE.Vector2();
const ground=new THREE.Plane(new THREE.Vector3(0,1,0),0);
const ghost=new THREE.Mesh(new THREE.BoxGeometry(5,.12,5),new THREE.MeshBasicMaterial({color:0xd5e7a4,transparent:true,opacity:.55,depthWrite:false}));
ghost.visible=false;scene.add(ghost);
let hasPointer=false;
let valid=false,point=new THREE.Vector3();
function locate(e){hasPointer=true;mouse.set(e.clientX/innerWidth*2-1,-e.clientY/innerHeight*2+1);ray.setFromCamera(mouse,camera);if(!ray.ray.intersectPlane(ground,point))return;point.x=Math.round(point.x/3)*3;point.z=Math.round(point.z/3)*3;valid=Math.abs(point.x)<44&&Math.abs(point.z)<44&&point.x>-18;const bs=world.buildings||[];for(const b of bs){const p=b.position||b;if(Number.isFinite(p.x)&&Math.hypot(p.x-point.x,p.z-point.z)<(b.radius||3)+(selected==='farm'?5:selected==='church'?5:3))valid=false;}ghost.position.set(point.x,.2,point.z);ghost.material.color.set(valid?'#d4e6a0':'#db7763');}
canvas.addEventListener('pointermove',e=>{if(selected)locate(e);});
let down;canvas.addEventListener('pointerdown',e=>{down={x:e.clientX,y:e.clientY};});
canvas.addEventListener('pointerup',e=>{if(e.button!==0||!selected||!down||Math.hypot(e.clientX-down.x,e.clientY-down.y)>5)return;locate(e);if(!valid){ui.notify('Busca terreno libre, lejos del río y de otros edificios.');return;}const result=sim.build(selected);if(result.ok){world.placeBuilding(selected,point.x,point.z);ui.notify(result.message);}else ui.notify(result.message);ui.update(sim.state);});
window.addEventListener('keydown',e=>{if(e.code==='Escape'){selected=null;sim.state.selected=null;ui.selectBuilding(null);}if(e.code==='Space'&&e.target===document.body){e.preventDefault();sim.togglePause();}if(/^Digit[1-6]$/.test(e.code)){const type=Object.keys(BUILDINGS)[Number(e.code.slice(-1))-1];selected=selected===type?null:type;sim.state.selected=selected;ui.selectBuilding(selected);}});
window.addEventListener('resize',()=>{camera.aspect=innerWidth/innerHeight;camera.updateProjectionMatrix();renderer.setSize(innerWidth,innerHeight);});
let last=performance.now(),elapsed=0,uiTime=0;
function frame(now){requestAnimationFrame(frame);const dt=Math.min((now-last)/1000,.1);last=now;elapsed+=sim.state.paused?0:dt*sim.state.speed;sim.update(dt);world.update(sim.state.paused?0:dt*sim.state.speed,elapsed);controls.update();ghost.visible=Boolean(selected)&&hasPointer;ghost.scale.setScalar(selected==='farm'||selected==='church'?2:1);uiTime+=dt;if(uiTime>.25){ui.update(sim.state);uiTime=0;}renderer.render(scene,camera);}
ui.update(sim.state);requestAnimationFrame(frame);
window.__littleTown={sim,world,renderer,scene,camera};
